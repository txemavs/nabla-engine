/** Generate renderer-independent catalog poses from authored GLB anchors. */
import fs from 'node:fs'
import path from 'node:path'
import { createHash } from 'node:crypto'
import { format } from 'prettier'
import { readGlbDocument, extractVehicleRig } from './lib/vehicle-rig.mjs'

const assets = path.resolve('assets')
const rigs = {}
for (const entry of fs.readdirSync('assets/library', { recursive: true }).sort()) {
  if (!entry.endsWith('.json')) continue
  const source = JSON.parse(fs.readFileSync(path.join('assets/library', entry), 'utf8'))
  if (source.rig !== 'glb') continue
  if (
    source.vehicle.hubs ||
    source.vehicle.driver ||
    source.vehicle.headOffset ||
    source.vehicle.headRotation ||
    source.visual.wheelRotations ||
    source.visual.steering?.transform
  )
    throw new Error(`Preset ${source.id} duplicates GLB-authored anchors in JSON`)
  const body = source.visual.body
  const file = path.resolve(assets, '.' + body.url)
  if (!file.startsWith(assets + path.sep)) throw new Error('Body asset escapes assets directory')
  const bytes = fs.readFileSync(file)
  if (rigs[source.id]) throw new Error(`Duplicate rig preset: ${source.id}`)
  rigs[source.id] = {
    source: body.url,
    sha256: createHash('sha256').update(bytes).digest('hex'),
    ...extractVehicleRig(readGlbDocument(bytes), body.transform),
  }
}
const destination = 'src/catalog/vehicles/generated-rigs.ts'
const output = await format(
  `/** Generated by scripts/generate-vehicle-rigs.mjs. Edit the GLB anchors, not this file. */
export const generatedVehicleRigs: Record<string, { source: string; sha256: string; hitch?: number[]; towAnchor?: number[]; hubs: number[][]; wheelRotations: number[][]; monitors?: { id: string; width: number; height: number; position: number[]; rotation: number[] }[]; driver?: number[]; headOffset?: number[]; headRotation?: number[]; steering?: { position: number[]; rotation: number[] } }> = ${JSON.stringify(rigs)}\n`,
  { parser: 'typescript', semi: false, singleQuote: true, printWidth: 100 },
)
if (process.argv.includes('--check')) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output)
    throw new Error('Vehicle rig data is stale. Run npm run rigs:generate.')
} else fs.writeFileSync(destination, output)
console.log(
  `Vehicle rigs: ${Object.keys(rigs).join(', ')} (${process.argv.includes('--check') ? 'verified' : 'generated'})`,
)
