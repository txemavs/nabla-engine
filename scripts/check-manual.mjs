/** Validate manual navigation and derive the public entry-point reference from package.json. */
import { readFile, writeFile, readdir, stat } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { format, resolveConfig } from 'prettier'

const root = fileURLToPath(new URL('../', import.meta.url))
const manual = path.join(root, 'docs/manual')
const packageFile = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))
const referencePath = path.join(manual, 'appendix-api.md')
const issues = []
const args = process.argv.slice(2)
if (args.some((arg) => arg !== '--write-reference')) {
  throw new Error('Usage: node scripts/check-manual.mjs [--write-reference]')
}

const rows = []
for (const [subpath, target] of Object.entries(packageFile.exports)) {
  const importTarget = typeof target === 'string' ? target : target.import
  const typeTarget = typeof target === 'object' ? target.types : undefined
  if (!importTarget?.startsWith('./dist/') || !importTarget.endsWith('.js')) {
    throw new Error(`Review manual generator for unsupported export shape: ${subpath}`)
  }
  const source = importTarget.replace('./dist/', 'src/').replace(/\.js$/, '.ts')
  await stat(path.join(root, source))
  const name = subpath === '.' ? packageFile.name : packageFile.name + subpath.slice(1)
  rows.push(
    `| \`${name}\` | [\`${source}\`](../../${source}) | \`${typeTarget ?? 'No declaration target'}\` |`,
  )
}
const rawReference = `# Appendix A. Public package entry points

[Manual contents](README.md)

Generated by \`node scripts/check-manual.mjs --write-reference\` from
[package.json](../../package.json). Do not edit this inventory by hand.
Package: **${packageFile.name} ${packageFile.version}**.

Each row is an exported package entry point, not a claim that every neighboring
source file is public. Follow its source exports and generated TypeScript declarations
for symbol signatures. Declaration paths below are package build outputs, produced
by \`npm run build\`.

The root entry includes scene/physics/presentation utilities and has a broad dependency
graph. Prefer a focused subpath when it fits the task. In particular,
\`runtime/core\` exports the shared gameplay coordinator named \`GameRuntime\`, while
\`runtime/browser\` exports the full browser composition of the same name. They are
different classes; preserve the import path in examples. Session ownership is
documented in [chapter 6](06-lifecycle.md), and integration levels in
[chapter 4](04-integration.md).

| Public import | Source entry | Declaration target |
| --- | --- | --- |
${rows.join('\n')}

## Looking up an API safely

1. Select the public import above.
2. Read that entry's exports and the linked implementation of the desired symbol.
3. Check its parameter units, state ownership, asynchronous behavior, and cleanup.
4. Build and typecheck a consumer using the public import.
5. Use [executable recipes](appendix-recipes.md) for integration evidence.

The list is exhaustive for package entry points at generation time; behavioral
coverage belongs to the chapters and examples. It does not promise that internal
symbols are stable or that an experimental entry is production-ready.
`
const prettier = (await resolveConfig(referencePath)) ?? {}
const expected = await format(rawReference, { ...prettier, filepath: referencePath })
if (args.includes('--write-reference')) await writeFile(referencePath, expected)
const current = await readFile(referencePath, 'utf8').catch(() => '')
if (current !== expected)
  issues.push('Public export reference is stale; run with --write-reference.')

const manualFiles = (await readdir(manual)).filter((name) => name.endsWith('.md')).sort()
const chapterFiles = manualFiles.filter((name) => /^\d{2}-/.test(name))
for (let number = 1; number <= 26; number++) {
  const prefix = `${String(number).padStart(2, '0')}-`
  if (chapterFiles.filter((name) => name.startsWith(prefix)).length !== 1)
    issues.push(`Expected exactly one chapter ${number}.`)
}
if (chapterFiles.length !== 26) issues.push('Expected 26 chapter files.')
const index = await readFile(path.join(manual, 'README.md'), 'utf8')
for (const chapter of chapterFiles) {
  if (!index.includes(`](${chapter})`)) issues.push(`Chapter missing from contents: ${chapter}`)
}

function headingIds(text) {
  const ids = new Set()
  const counts = new Map()
  for (const line of text.replace(/```[\s\S]*?```/g, '').split(/\r?\n/)) {
    const match = /^#{1,6}\s+(.+?)\s*#*\s*$/.exec(line)
    if (!match) continue
    const base = match[1]
      .toLowerCase()
      .replace(/<[^>]*>/g, '')
      .replace(/[^\p{L}\p{N}_\-\s]/gu, '')
      .replace(/ /g, '-')
    const count = counts.get(base) ?? 0
    ids.add(count ? `${base}-${count}` : base)
    counts.set(base, count + 1)
  }
  return ids
}

let links = 0
const files = [
  ...manualFiles.map((name) => path.join(manual, name)),
  path.join(root, 'examples/manual/README.md'),
]
for (const file of files) {
  const text = await readFile(file, 'utf8')
  for (const match of text.matchAll(/!?\[[^\]]*\]\(([^)]+)\)/g)) {
    const href = match[1].replace(/^<|>$/g, '')
    if (/^[a-z][a-z\d+.-]*:/i.test(href) || href.startsWith('//')) continue
    links++
    const [pathname, fragment] = href.split('#')
    const target = pathname ? path.resolve(path.dirname(file), decodeURIComponent(pathname)) : file
    try {
      const info = await stat(target)
      if (fragment && info.isFile() && target.endsWith('.md')) {
        const targetText = await readFile(target, 'utf8')
        if (!headingIds(targetText).has(decodeURIComponent(fragment)))
          issues.push(`${path.relative(root, file)}: missing heading ${href}`)
      }
    } catch {
      issues.push(`${path.relative(root, file)}: missing local target ${href}`)
    }
  }
}

if (issues.length) {
  console.error(issues.join('\n'))
  process.exitCode = 1
} else {
  console.log(
    `Manual OK: ${chapterFiles.length} chapters, ${files.length} Markdown files, ${links} local links, ${rows.length} public entry points.`,
  )
}
