/**
 * Installable web app (PWA) building blocks. Pure functions that return the web app manifest,
 * the service worker source, the offline page and the `<head>` tags; hosts configure them and
 * serve the results (see `scripts/vite-pwa.ts` for the Vite plugin that does it).
 *
 * The service worker only ever caches the app shell it is given (offline page, manifest,
 * icons). Navigations go to the network first and fall back to the offline page; every other
 * request, terrain tiles and game bundles included, is left to the browser and its HTTP cache.
 */

/** One manifest icon. `purpose: 'maskable'` icons keep their content in the inner 80 % circle. */
export interface PwaIcon {
  src: string
  /** `WxH`, e.g. `192x192`. */
  sizes: string
  type?: string
  purpose?: 'any' | 'maskable' | 'monochrome'
}

export interface PwaManifestOptions {
  name: string
  shortName: string
  description?: string
  /** Stable app identity. Default `startUrl`. */
  id?: string
  /** Default `/`. */
  startUrl?: string
  /** Default `/`. */
  scope?: string
  /** Default `fullscreen`, with `standalone` as the fallback where fullscreen is not supported. */
  display?: 'fullscreen' | 'standalone' | 'minimal-ui' | 'browser'
  orientation?: 'any' | 'landscape' | 'portrait'
  /** Default `#000000`. */
  themeColor?: string
  /** Default `#000000`. */
  backgroundColor?: string
  lang?: string
  categories?: readonly string[]
  icons: readonly PwaIcon[]
}

/** Web app manifest (serve as `application/manifest+json`). */
export function webAppManifest(options: PwaManifestOptions): Record<string, unknown> {
  const startUrl = options.startUrl ?? '/'
  const display = options.display ?? 'fullscreen'
  return {
    id: options.id ?? startUrl,
    name: options.name,
    short_name: options.shortName,
    ...(options.description ? { description: options.description } : {}),
    ...(options.lang ? { lang: options.lang } : {}),
    start_url: startUrl,
    scope: options.scope ?? '/',
    display,
    ...(display === 'fullscreen' ? { display_override: ['fullscreen', 'standalone'] } : {}),
    ...(options.orientation ? { orientation: options.orientation } : {}),
    theme_color: options.themeColor ?? '#000000',
    background_color: options.backgroundColor ?? '#000000',
    ...(options.categories?.length ? { categories: [...options.categories] } : {}),
    icons: options.icons.map((icon) => ({
      src: icon.src,
      sizes: icon.sizes,
      type: icon.type ?? 'image/png',
      purpose: icon.purpose ?? 'any',
    })),
  }
}

export interface ServiceWorkerOptions {
  /**
   * Cache name. Put a content version in it (e.g. a hash of the shell): a new name makes the
   * worker drop the caches of older versions on activation.
   */
  cacheName: string
  /** Prefix shared by every cache of this app; caches with it and another name are deleted. */
  cachePrefix: string
  /** Same-origin URLs cached on install and answered cache-first (stale-while-revalidate). */
  shell: readonly string[]
  /** Page answered to navigations when the network fails (must be in `shell`). */
  offlineUrl: string
}

/**
 * Service worker source. Only GET requests to the worker's own origin are looked at: navigations
 * (network first, offline page on failure) and the shell URLs. Cross-origin requests (tile CDN)
 * and every other same-origin URL (bundles, `/tiles` proxy, music) never touch its cache.
 */
export function serviceWorkerSource(options: ServiceWorkerOptions): string {
  if (!options.shell.includes(options.offlineUrl))
    throw new Error('serviceWorkerSource: offlineUrl must be part of shell')
  const config = JSON.stringify({
    cache: options.cacheName,
    prefix: options.cachePrefix,
    shell: [...options.shell],
    offline: options.offlineUrl,
  })
  return `/* Generated by @nabla/engine/pwa: caches the app shell only. */
const CONFIG = ${config};
const SHELL = new Set(CONFIG.shell.map((path) => new URL(path, self.location.origin).href));

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CONFIG.cache).then((cache) => cache.addAll(CONFIG.shell)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((names) => Promise.all(names.filter((name) => name.startsWith(CONFIG.prefix) && name !== CONFIG.cache).map((name) => caches.delete(name))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(() => caches.match(CONFIG.offline, { cacheName: CONFIG.cache })));
    return;
  }
  url.search = '';
  if (!SHELL.has(url.href)) return;
  event.respondWith(
    caches.open(CONFIG.cache).then(async (cache) => {
      const cached = await cache.match(url.href);
      const fresh = fetch(request).then((response) => {
        if (response.ok) void cache.put(url.href, response.clone());
        return response;
      });
      if (!cached) return fresh;
      event.waitUntil(fresh.catch(() => undefined));
      return cached;
    }),
  );
});
`
}

export interface PwaHeadOptions {
  manifestUrl: string
  serviceWorkerUrl: string
  /** Default `#000000`. */
  themeColor?: string
  /** Home screen title on iOS. */
  appTitle: string
  /** 180×180 PNG for iOS (opaque, no rounding: iOS rounds it). */
  appleTouchIcon: string
  /** Optional PNG favicon. */
  icon?: string
}

/**
 * `<head>` tags: manifest link, theme colour, iOS home screen tags, the service worker
 * registration and the early `beforeinstallprompt` capture. The event is kept as
 * `window.nablaInstallPrompt` and announced with a `nabla-installable` window event, so an
 * install button mounted later still gets it (see `runtime/pwa-install.ts`).
 */
export function pwaHeadTags(options: PwaHeadOptions): string {
  const attr = (value: string) =>
    value.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;')
  const theme = attr(options.themeColor ?? '#000000')
  return [
    `<link rel="manifest" href="${attr(options.manifestUrl)}">`,
    `<meta name="theme-color" content="${theme}">`,
    `<meta name="mobile-web-app-capable" content="yes">`,
    `<meta name="apple-mobile-web-app-capable" content="yes">`,
    `<meta name="apple-mobile-web-app-status-bar-style" content="black">`,
    `<meta name="apple-mobile-web-app-title" content="${attr(options.appTitle)}">`,
    `<link rel="apple-touch-icon" href="${attr(options.appleTouchIcon)}">`,
    options.icon ? `<link rel="icon" type="image/png" href="${attr(options.icon)}">` : '',
    `<script>(() => {` +
      ` addEventListener('beforeinstallprompt', (event) => { event.preventDefault(); window.nablaInstallPrompt = event; dispatchEvent(new Event('nabla-installable')); });` +
      ` addEventListener('appinstalled', () => { window.nablaInstallPrompt = undefined; });` +
      ` if ('serviceWorker' in navigator) addEventListener('load', () => { navigator.serviceWorker.register(${JSON.stringify(options.serviceWorkerUrl)}, { scope: '/' }).catch((error) => console.warn('[pwa] service worker', error)); });` +
      ` })();</script>`,
  ].join('')
}

/** Texts of the offline page in one language. */
export interface OfflineTexts {
  title: string
  message: string
  retry: string
}

export interface OfflinePageOptions {
  appName: string
  /** Texts by locale; `en` is required and is the fallback. */
  texts: Readonly<Record<string, OfflineTexts>> & { en: OfflineTexts }
  /** Optional icon shown above the texts (a shell URL, so it is cached). */
  iconUrl?: string
  /** Default `#000000`. */
  background?: string
  /** Default `#ffffff`. */
  color?: string
}

/**
 * Self-contained offline page (no external CSS or scripts). The language follows `?locale=` or
 * the browser language, English otherwise; «Retry» reloads the start address.
 */
export function offlinePageHtml(options: OfflinePageOptions): string {
  const escape = (value: string) =>
    value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
  const en = options.texts.en
  const texts = JSON.stringify(options.texts).replace(/</g, '\\u003c')
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="theme-color" content="${escape(options.background ?? '#000000')}">
<title>${escape(options.appName)}</title>
<style>
html,body{height:100%;margin:0}
body{display:flex;flex-direction:column;align-items:center;justify-content:center;gap:18px;padding:24px;box-sizing:border-box;background:${escape(options.background ?? '#000000')};color:${escape(options.color ?? '#ffffff')};font:16px/1.4 Arial,sans-serif;text-align:center}
img{width:72px;height:72px}
h1{margin:0;font-size:20px;letter-spacing:.08em}
p{margin:0;max-width:32em;opacity:.78}
button{font:inherit;letter-spacing:.3em;padding:.6em 1.4em .6em 1.7em;color:inherit;background:none;border:1px solid currentColor;border-radius:2px;cursor:pointer}
</style>
</head>
<body>
${options.iconUrl ? `<img src="${escape(options.iconUrl)}" alt="">` : ''}
<h1 id="title">${escape(en.title)}</h1>
<p id="message">${escape(en.message)}</p>
<button id="retry" type="button">${escape(en.retry)}</button>
<script>
(() => {
  const texts = ${texts};
  const wanted = [new URLSearchParams(location.search).get('locale'), ...(navigator.languages || [navigator.language])];
  const locale = wanted.map((code) => String(code || '').slice(0, 2).toLowerCase()).find((code) => texts[code]) || 'en';
  const text = texts[locale];
  document.documentElement.lang = locale;
  for (const key of ['title', 'message', 'retry']) document.getElementById(key).textContent = text[key];
  document.getElementById('retry').addEventListener('click', () => location.reload());
  addEventListener('online', () => location.reload());
})();
</script>
</body>
</html>
`
}
